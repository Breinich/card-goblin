#!/usr/bin/env node

/**
 * Deterministically discover owner-authored starter project files and emit the
 * metadata-only client registry. Project payloads stay behind literal dynamic
 * imports in the generated module, so adding a base64-heavy starter does not
 * eagerly add it to /editor's initial JavaScript.
 *
 * Ordinary generation permits missing owner-authored files while this feature
 * is under construction. `--strict` is the release/CI posture: every required
 * file must exist. `--check` verifies that committed generated output is fresh
 * without rewriting it.
 */

import { fileURLToPath, pathToFileURL } from "node:url";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

export const STARTER_PROJECT_SOURCES = Object.freeze([
  Object.freeze({
    id: "poker-deck",
    label: "Poker Deck",
    suggestedName: "Poker Deck",
    filename: "poker-deck.cardgoblin.json",
  }),
  Object.freeze({
    id: "tcg",
    label: "TCG",
    suggestedName: "TCG",
    filename: "tcg.cardgoblin.json",
  }),
  Object.freeze({
    id: "party-game",
    label: "Party Game",
    suggestedName: "Party Game",
    filename: "party-game.cardgoblin.json",
  }),
]);

const GENERATED_HEADER = `/*
 * GENERATED by scripts/generate-starter-projects.mjs.
 * Do not edit this file. Edit template_projects/*.cardgoblin.json and rerun
 * npm run generate:starter-projects instead.
 */`;

function quoted(value) {
  return JSON.stringify(value);
}

function assertKnownUniqueFileNames(fileNames) {
  const seen = new Set();
  const allowed = new Set(STARTER_PROJECT_SOURCES.map((source) => source.filename));
  for (const filename of fileNames) {
    if (seen.has(filename)) {
      throw new Error(`Duplicate starter project source: ${filename}`);
    }
    seen.add(filename);
    if (!allowed.has(filename)) {
      throw new Error(
        `Unexpected starter project file '${filename}'. Expected only: ${[...allowed].join(", ")}.`,
      );
    }
  }
  return seen;
}

function renderAvailableSource(source) {
  return `  {
    id: ${quoted(source.id)},
    label: ${quoted(source.label)},
    suggestedName: ${quoted(source.suggestedName)},
    sourceFile: ${quoted(source.filename)},
    available: true,
    load: async () => {
      const [projectModule, projectFile] = await Promise.all([
        import(${quoted(`../../../../template_projects/${source.filename}`)}),
        import("../_lib/projectFileFormat"),
      ]);
      const parsed = projectFile.parseImportedProjectFile(JSON.stringify(projectModule.default));
      if ("error" in parsed) {
        throw new Error(${quoted(`Bundled starter '${source.label}' is not a readable CardGoblin project file.`)});
      }
      return parsed;
    },
  },`;
}

function renderUnavailableSource(source) {
  return `  {
    id: ${quoted(source.id)},
    label: ${quoted(source.label)},
    suggestedName: ${quoted(source.suggestedName)},
    sourceFile: ${quoted(source.filename)},
    available: false,
    load: null,
  },`;
}

/** Pure renderer exported for the determinism test. Input order is ignored. */
export function renderStarterRegistry(fileNames) {
  const present = assertKnownUniqueFileNames(fileNames);
  const records = STARTER_PROJECT_SOURCES.map((source) =>
    present.has(source.filename)
      ? renderAvailableSource(source)
      : renderUnavailableSource(source),
  );

  return `${GENERATED_HEADER}

import type { GeneratedStarterProject } from "../_lib/starterProjects";

export const generatedStarterProjects = [
${records.join("\n")}
] as const satisfies readonly GeneratedStarterProject[];
`;
}

export async function discoverStarterFileNames(templateDirectory) {
  const entries = await readdir(templateDirectory, { withFileTypes: true });
  const projectEntries = entries.filter((entry) => entry.name.endsWith(".cardgoblin.json"));
  const nonFiles = projectEntries.filter((entry) => !entry.isFile());
  if (nonFiles.length > 0) {
    throw new Error(
      `Starter project sources must be regular files: ${nonFiles.map((entry) => entry.name).join(", ")}.`,
    );
  }
  const names = projectEntries.map((entry) => entry.name);
  assertKnownUniqueFileNames(names);
  return STARTER_PROJECT_SOURCES
    .map((source) => source.filename)
    .filter((filename) => names.includes(filename));
}

export async function generateStarterProjects({ rootDirectory, check = false, strict = false }) {
  const templateDirectory = path.join(rootDirectory, "template_projects");
  const outputPath = path.join(
    rootDirectory,
    "src/app/editor/_generated/starterProjects.generated.ts",
  );
  const present = await discoverStarterFileNames(templateDirectory);
  const missing = STARTER_PROJECT_SOURCES
    .map((source) => source.filename)
    .filter((filename) => !present.includes(filename));

  if (strict && missing.length > 0) {
    throw new Error(`Missing required starter project files: ${missing.join(", ")}.`);
  }

  const expected = renderStarterRegistry(present);
  if (check) {
    let actual;
    try {
      actual = await readFile(outputPath, "utf8");
    } catch {
      throw new Error(`Generated starter registry is missing: ${outputPath}`);
    }
    if (actual !== expected) {
      throw new Error(
        "Generated starter registry is stale. Run npm run generate:starter-projects and commit the result.",
      );
    }
    return { outputPath, present, missing, wrote: false };
  }

  let actual = null;
  try {
    actual = await readFile(outputPath, "utf8");
  } catch {
    // First generation writes the file below.
  }
  if (actual !== expected) await writeFile(outputPath, expected, "utf8");
  return { outputPath, present, missing, wrote: actual !== expected };
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const unknown = [...args].filter((arg) => arg !== "--check" && arg !== "--strict");
  if (unknown.length > 0) throw new Error(`Unknown option(s): ${unknown.join(", ")}`);

  const rootDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const result = await generateStarterProjects({
    rootDirectory,
    check: args.has("--check"),
    strict: args.has("--strict"),
  });
  const state = result.present.length === 0 ? "none present" : result.present.join(", ");
  process.stdout.write(`Starter registry ready (${state}).\n`);
}

const isEntrypoint = process.argv[1]
  ? import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
  : false;

if (isEntrypoint) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
